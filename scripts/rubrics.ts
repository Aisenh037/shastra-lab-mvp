// Validate rubric files and turn them into SQL you can paste into the Supabase SQL editor.
//
//   node scripts/rubrics.ts validate           # check every rubrics/*.json
//   node scripts/rubrics.ts sql > rubrics.sql  # upserts for every valid file
//
// A file matches its question by exact question text among the PYQ template questions.
// Only files with "status": "reviewed" are used by the evaluator; drafts are stored but ignored.

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { validateRubric, type Rubric } from "../supabase/functions/_shared/rubric.ts";

interface RubricFile {
  match: { questionText: string };
  status: "draft" | "reviewed";
  reviewedBy: string | null;
  rubric: Rubric;
}

const dir = join(import.meta.dirname, "..", "rubrics");
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

function load(): Array<{ file: string; data: RubricFile; errors: string[] }> {
  return files.map((file) => {
    try {
      const data = JSON.parse(readFileSync(join(dir, file), "utf8")) as RubricFile;
      const errors = [...validateRubric(data.rubric).errors];
      if (!data.match?.questionText?.trim()) errors.push("match.questionText is required");
      if (!["draft", "reviewed"].includes(data.status)) errors.push('status must be "draft" or "reviewed"');
      if (data.status === "reviewed" && !data.reviewedBy) errors.push("reviewed rubrics need reviewedBy (the mentor's name)");
      if (data.status === "reviewed" && data.rubric?.source !== "reviewed") errors.push('set rubric.source to "reviewed" when status is reviewed');
      return { file, data, errors };
    } catch (e) {
      return { file, data: null as unknown as RubricFile, errors: [`invalid JSON: ${(e as Error).message}`] };
    }
  });
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const cmd = process.argv[2];
const results = load();

if (cmd === "validate") {
  let bad = 0;
  for (const r of results) {
    if (r.errors.length) {
      bad++;
      console.log(`✗ ${r.file}\n  - ${r.errors.join("\n  - ")}`);
    } else {
      const points = r.data.rubric.dimensions.reduce((n, d) => n + d.points.length, 0);
      console.log(`✓ ${r.file} (${r.data.status}, ${points} points)`);
    }
  }
  console.log(`\n${results.length - bad}/${results.length} valid`);
  process.exit(bad ? 1 : 0);
} else if (cmd === "sql") {
  const valid = results.filter((r) => r.errors.length === 0);
  const out = ["-- Generated by scripts/rubrics.ts. Safe to re-run.", "BEGIN;"];
  for (const { file, data } of valid) {
    out.push(
      `-- ${file}`,
      `INSERT INTO public.question_rubrics (question_id, rubric, status, reviewed_by, updated_at)
SELECT pq.id, ${q(JSON.stringify(data.rubric))}::jsonb, ${q(data.status)}, ${data.reviewedBy ? q(data.reviewedBy) : "NULL"}, now()
FROM public.practice_questions pq
JOIN public.mock_tests mt ON mt.id = pq.mock_test_id AND mt.is_template = true
WHERE pq.question_text = ${q(data.match.questionText)}
ON CONFLICT (question_id) DO UPDATE SET rubric = EXCLUDED.rubric, status = EXCLUDED.status, reviewed_by = EXCLUDED.reviewed_by, updated_at = now();`,
    );
  }
  out.push("COMMIT;");
  console.log(out.join("\n"));
  const skipped = results.length - valid.length;
  if (skipped) console.error(`skipped ${skipped} invalid file(s); run "validate" to see why`);
} else {
  console.error("usage: node scripts/rubrics.ts validate | sql");
  process.exit(2);
}

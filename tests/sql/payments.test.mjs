import { check, done, freshDb, throws } from "./harness.mjs";

const { q } = await freshDb();
const u = (await q(`insert into auth.users(email) values ('a@x.in') returning id`))[0].id;
const bal = async () => (await q(`select balance from evaluation_credits where user_id='${u}'`))[0]?.balance;
await q(`insert into payment_orders(id,user_id,pack_id,credits,amount_paise) values ('order_A','${u}','standard',10,19900),('order_B','${u}','starter',5,9900)`);
const f = async (o,p,a,v='checkout') => (await q(`select fulfil_payment_order('${o}','${p}',${a},'${v}') as r`))[0].r;
check("packs seeded", (await q(`select count(*)::int n from credit_packs where active`))[0].n===3);
let r = await f('order_A','pay_1',19900);
check("paid: trial 1 + 10", r.outcome==='paid' && r.balance===11 && await bal()===11, r);
r = await f('order_A','pay_1',19900,'webhook');
check("webhook after checkout: no double credit", r.outcome==='already_paid' && await bal()===11, r);
r = await f('order_B','pay_2',100);
check("wrong amount not credited", r.outcome==='amount_mismatch' && await bal()===11, r);
check("order stays unpaid after mismatch", (await q(`select status from payment_orders where id='order_B'`))[0].status==='created');
r = await f('order_X','pay_3',9900);
check("unknown order", r.outcome==='unknown_order', r);
await q(`select fail_payment_order('order_A')`);
check("fail never downgrades a paid order", (await q(`select status from payment_orders where id='order_A'`))[0].status==='paid');
await q(`select fail_payment_order('order_B')`);
check("fail marks unpaid order failed", (await q(`select status from payment_orders where id='order_B'`))[0].status==='failed');
const rf = async (p,rid,a) => (await q(`select refund_payment('${p}','${rid}',${a}) as r`))[0].r;
r = await rf('pay_1','rfnd_1',9950);
check("half refund takes 5 credits", r.outcome==='refunded' && r.credits_taken===5 && await bal()===6, r);
r = await rf('pay_1','rfnd_1',9950);
check("same refund twice is a no-op", r.outcome==='duplicate' && await bal()===6, r);
await q(`update evaluation_credits set balance=2 where user_id='${u}'`);
r = await rf('pay_1','rfnd_2',9950);
check("refund can't take used credits (floor at 0)", r.credits_taken===2 && await bal()===0, r);
check("order fully refunded", (await q(`select status, refunded_credits from payment_orders where id='order_A'`))[0].status==='refunded');
r = await f('order_A','pay_1',19900,'webhook');
check("refunded order never re-credited", r.outcome==='already_paid' && await bal()===0, r);
check("ledger trail", (await q(`select string_agg(reason||':'||delta, ',' order by created_at) s from credit_ledger`))[0].s==='free_trial:1,purchase:10,adjustment:-5,adjustment:-2');
const grants = await q(`select distinct grantee from information_schema.routine_privileges where routine_name in ('fulfil_payment_order','fail_payment_order','refund_payment') and grantee<>'postgres'`);
check("service_role only", grants.length===1 && grants[0].grantee==='service_role', grants);
done();
